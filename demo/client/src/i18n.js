function readSavedLang() {
  try {
    return localStorage.getItem(LANG_KEY) === "ta" ? "ta" : "en";
  } catch {
    return "en";
  }
}

export function useLang() {
  const [lang, setLangState] = useState(readSavedLang);
  const setLang = useCallback((next) => {
    setLangState(next);
    try {
      localStorage.setItem(LANG_KEY, next);
    } catch {
      // private mode / blocked storage: the choice still applies for this visit
    }
  }, []);
  return [lang, setLang];
}

export function t(lang, key, vars) {
  const text = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (match, name) => vars[name] ?? match) : text;
}
