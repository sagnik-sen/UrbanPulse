import { useCallback, useEffect, useState } from "react";

// seconds to "Xm Ys", or "Xh Ym" from an hour up
function fmt(sec) {
  if (sec == null) return "—";
  const m = Math.floor(sec / 60);
  return m >= 60 ? `${Math.floor(m / 60)}h ${m % 60}m` : `${m}m ${sec % 60}s`;
}

const at = (ev) => (ev ? `+${fmt(ev.afterSec)}` : "—");

export default function Accountability() {
  const [data, setData] = useState(null);
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(false);

  const load = useCallback(() => {
    setLoading(true);
    return fetch("/api/accountability")
      .then(async (res) => {
        const body = await res.json();
        if (!res.ok) throw new Error(body.error || `Request failed (${res.status})`);
        setData(body);
        setError("");
      })
      .catch((err) => setError(err.message))
      .finally(() => setLoading(false));
  }, []);

  useEffect(() => { load(); }, [load]);

  const s = data?.summary;
  const kpis = [
    ["Incidents", s?.incidents ?? "—"],
    ["Dispatched", s?.dispatchedPct == null ? "—" : `${s.dispatchedPct}%`],
    ["Median time to dispatch", fmt(s?.medianDispatchSec)],
    ["Median time to evacuation order", fmt(s?.medianEvacuationSec)],
    ["Median incident duration", fmt(s?.medianDurationSec)],
  ];

  return (
    <>
      <section className="panel">
        <div className="panel-head">
          <h2>Accountability</h2>
          <button className="btn ghost" onClick={load} disabled={loading}>{loading ? "Refreshing…" : "Refresh"}</button>
        </div>
        <p className="muted small" style={{ marginBottom: 12 }}>
          Times come from the tamper-evident audit log. In this demo they are generated by the simulator and staff actions, not real incidents. The first automated alert is sent the moment an incident opens, so its time is 0 by design.
        </p>
        {error && <div className="form-error" role="alert">{error}</div>}
      </section>

      <section className="kpi-row">
        {kpis.map(([label, value]) => (
          <div className="kpi" key={label}>
            <div className="kpi-label">{label}</div>
            <div className="kpi-value">{value}</div>
          </div>
        ))}
      </section>

      <section className="panel">
        {!data ? (
          <div className="empty">Loading…</div>
        ) : data.timelines.length === 0 ? (
          <div className="empty">No incidents in the audit log yet.</div>
        ) : (
          <table className="table">
            <thead><tr><th>Zone</th><th>Opened</th><th>Alert</th><th>Dispatch</th><th>Evacuation order</th><th>Cleared</th><th>Sealed</th></tr></thead>
            <tbody>
              {data.timelines.map((t) => (
                <tr key={t.incidentId}>
                  <td>{t.zone}</td>
                  <td className="mono">{new Date(t.openedAt).toLocaleString()}</td>
                  <td>{at(t.events.alert)}</td>
                  <td>{at(t.events.dispatch)}</td>
                  <td>{at(t.events.evacuation)}</td>
                  <td>{at(t.events.cleared)}</td>
                  <td>{t.sealed ? <span className="audit-tag ok">✓ Sealed</span> : <span className="audit-tag neutral">Pending</span>}</td>
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </section>
    </>
  );
}
